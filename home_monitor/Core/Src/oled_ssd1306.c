/* 可配置项 ----------------------------------------------------------------*/
#define OLED_I2C            hi2c1
#define OLED_ADDR           0x78    // 7位地址左移1位（0x3C << 1）

/* 私有变量 ----------------------------------------------------------------*/
static uint8_t buffer[OLED_WIDTH * OLED_HEIGHT / 8];  // 1024 bytes

/* 外部变量 ----------------------------------------------------------------*/
extern I2C_HandleTypeDef OLED_I2C;

/* 私有函数 ----------------------------------------------------------------*/

static void OLED_WriteCmd(uint8_t cmd)
{
    uint8_t data[] = {0x00, cmd};
    HAL_I2C_Master_Transmit(&OLED_I2C, OLED_ADDR, data, 2, 100);
}

static void OLED_WriteData(uint8_t dat)
{
    uint8_t data[] = {0x40, dat};
    HAL_I2C_Master_Transmit(&OLED_I2C, OLED_ADDR, data, 2, 100);
}

